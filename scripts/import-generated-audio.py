#!/usr/bin/env python3
"""One-time import of generated, privately linked audio on a GitHub runner.

This script is not called by the game. Results are committed as local assets.
The temporary download manifest is removed from git after a successful import.
"""
import hashlib
import json
import pathlib
import subprocess
import sys
import urllib.request
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parents[1]
INPUT = ROOT / ".github" / "one-time-audio-sources.json"
DEST = ROOT / "public" / "audio"
CUES = {
    "train-whistle", "train-chug", "steam-release", "track-lay",
    "depot-build", "city-build", "coin-clink", "dice-roll",
    "clash-impact", "crowd-gasp", "crowd-cheer", "era-fanfare",
    "victory-fanfare", "ui-select", "ui-confirm",
    "ambience-railway", "music-parlour"
}


def validate_audio(path: pathlib.Path, expected: float) -> dict:
    probe = json.loads(subprocess.check_output(
        ["ffprobe", "-v", "error", "-show_entries",
         "stream=codec_name,sample_rate,channels:format=duration",
         "-of", "json", str(path)], text=True))
    audio = [s for s in probe.get("streams", []) if s.get("codec_name")]
    duration = float(probe["format"]["duration"])
    if not audio or audio[0]["codec_name"] != "mp3":
        raise ValueError(f"{path.name}: expected valid MP3 audio")
    if duration < max(0.25, expected * 0.65) or duration > expected * 2:
        raise ValueError(f"{path.name}: unexpected {duration:.2f}s, requested {expected}s")
    return {
        "duration_seconds": round(duration, 3),
        "codec": audio[0]["codec_name"],
        "sample_rate": int(audio[0]["sample_rate"]),
        "channels": int(audio[0]["channels"]),
        "size_bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest()
    }


def main():
    items = json.loads(INPUT.read_text())["items"]
    names = [x["name"] for x in items]
    if len(items) != len(CUES) or set(names) != CUES or len(names) != len(set(names)):
        raise ValueError("Generation manifest must contain all 17 allowed cues exactly once")
    DEST.mkdir(exist_ok=True, parents=True)
    inventory = []
    for i, item in enumerate(items, 1):
        name = item["name"]
        url = item["url"]
        if not url.startswith(("https://mirelo.ai/dl/", "https://api.sonilo.com/files/")):
            raise ValueError(f"{name}: unapproved download endpoint")
        final = DEST / (name + ".mp3")
        temp = DEST / (name + ".mp3.download")
        print(f"Downloading {i}/17: {name}", flush=True)
        request = urllib.request.Request(url, headers={"User-Agent": "IronCrownAssetImporter/1.8.1"})
        try:
            with urllib.request.urlopen(request, timeout=90) as resp, temp.open("wb") as out:
                while True:
                    data = resp.read(1024 * 256)
                    if not data:
                        break
                    out.write(data)
                    if out.tell() > 20_000_000:
                        raise ValueError(f"{name}: audio exceeds 20 MB limit")
            metadata = validate_audio(temp, float(item["expected_duration_seconds"]))
            temp.replace(final)
        finally:
            temp.unlink(missing_ok=True)
        inventory.append({
            "file": final.name, "provider": item["provider"],
            "generation_task": item["task_id"], **metadata
        })
    (DEST / "GENERATED-ASSETS.json").write_text(json.dumps({
        "schema": 1,
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "files": inventory,
        "note": "Sound recordings generated by Mirelo and music by Sonilo; provenance in AUDIO-LICENCES.md."
    }, indent=2) + "\n")
    print("VERIFIED: 17/17 generated MP3 files. Asset inventory written.", flush=True)


if __name__ == "__main__":
    main()
